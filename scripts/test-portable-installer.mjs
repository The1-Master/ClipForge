import assert from 'node:assert/strict';
import { existsSync, linkSync, mkdirSync, readFileSync, renameSync, symlinkSync, unlinkSync, writeFileSync } from 'node:fs';
import { spawn, spawnSync } from 'node:child_process';
import path from 'node:path';

const installer = path.resolve(process.argv[2] ?? 'J:/CS2ClipStudio/artifacts/ClipForge-0.3.0-public/ClipForge-0.3.0-Setup.exe');
assert(installer.startsWith(path.resolve('J:/CS2ClipStudio/artifacts') + path.sep));
const root = path.resolve('J:/CS2ClipStudio/temp/public-installer-tests', new Date().toISOString().replaceAll(':', '-'));
mkdirSync(root, { recursive: true });
const installed = path.join(root, 'Installed ClipForge');
const env = { ...process.env, TEMP: root, TMP: root, CLIPFORGE_WORKSPACE: installed, PYTHONPATH: '', PYTHONHOME: '', PYTHONNOUSERSITE: '1', PYTHONDONTWRITEBYTECODE: '1', APPDATA: path.join(root, 'appdata'), LOCALAPPDATA: path.join(root, 'localappdata') };
function run(file, args) { return spawnSync(file, args, { encoding: 'utf8', timeout: 60000, windowsHide: true, windowsVerbatimArguments: /(?:Setup|Uninstall-ClipForge)\.exe$/i.test(file), env }); }
const result = run(installer, ['/S', '/FIXTURE', `/D=${installed}`]);
assert.equal(result.status, 0, result.stderr);
assert(existsSync(path.join(installed, 'ClipForge.exe')));
assert(existsSync(path.join(installed, 'Uninstall-ClipForge.exe')));
const lockScript = 'import ctypes,sys\nfrom ctypes import wintypes\nk=ctypes.windll.kernel32\nk.CreateFileW.restype=wintypes.HANDLE\nk.CreateFileW.argtypes=[wintypes.LPCWSTR,wintypes.DWORD,wintypes.DWORD,wintypes.LPVOID,wintypes.DWORD,wintypes.DWORD,wintypes.HANDLE]\nh=k.CreateFileW(sys.argv[1],0x80000000,0,None,3,0,None)\nassert h!=wintypes.HANDLE(-1).value\nprint("locked",flush=True)\nsys.stdin.read()\nk.CloseHandle.argtypes=[wintypes.HANDLE]\nk.CloseHandle(h)';
const locker = spawn(path.join(installed, 'tools/python/python.exe'), ['-I', '-B', '-c', lockScript, path.join(installed, 'ClipForge.exe')], { env, windowsHide: true, stdio: ['pipe', 'pipe', 'pipe'] });
try {
  await new Promise((resolve, reject) => {
    const timeout = setTimeout(() => reject(new Error('Owned fixture lock did not become ready')), 10000);
    locker.stdout.once('data', chunk => { clearTimeout(timeout); chunk.toString().includes('locked') ? resolve() : reject(new Error('Unexpected lock fixture response')); });
    locker.once('error', reject);
    locker.once('exit', code => { if (code) { clearTimeout(timeout); reject(new Error('Owned lock fixture failed')); } });
  });
  const busy = run(installer, ['/S', '/FIXTURE', `/D=${installed}`]);
  assert.equal(busy.status, 3);
  assert(existsSync(path.join(installed, 'ClipForge.exe')));
  const busyUninstall = run(path.join(installed, 'Uninstall-ClipForge.exe'), ['/S', '/FIXTURE', `_?=${installed}`]);
  assert.equal(busyUninstall.status, 3);
  assert(existsSync(path.join(installed, 'ClipForge.exe')));
} finally {
  const ended = locker.exitCode === null && locker.signalCode === null ? new Promise(resolve => locker.once('exit', resolve)) : Promise.resolve();
  locker.stdin.end();
  await ended;
}
mkdirSync(path.join(installed, 'data/preserved'), { recursive: true });
mkdirSync(path.join(installed, 'tools/user-installed'), { recursive: true });
writeFileSync(path.join(installed, 'data/preserved/example.txt'), 'fixture user data');
writeFileSync(path.join(installed, 'tools/user-installed/custom.txt'), 'fixture downloaded helper');
const update = run(installer, ['/S', '/FIXTURE', `/D=${installed}`]);
assert.equal(update.status, 0, update.stderr);
assert.equal(readFileSync(path.join(installed, 'data/preserved/example.txt'), 'utf8'), 'fixture user data');
assert.equal(readFileSync(path.join(installed, 'tools/user-installed/custom.txt'), 'utf8'), 'fixture downloaded helper');
const uninstallAlias = path.join(root, 'Uninstall alias');
symlinkSync(installed, uninstallAlias, 'junction');
assert.equal(run(path.join(installed, 'Uninstall-ClipForge.exe'), ['/S', '/FIXTURE', `_?=${uninstallAlias}`]).status, 4);
assert(existsSync(path.join(installed, 'ClipForge.exe')));
assert.equal(readFileSync(path.join(installed, 'data/preserved/example.txt'), 'utf8'), 'fixture user data');
unlinkSync(uninstallAlias);
const packageModule = path.join(installed, 'tools/python/Lib/site-packages/psutil');
const preservedModule = path.join(installed, 'tools/python/Lib/site-packages/psutil-preserved-fixture');
const protectedTarget = path.join(root, 'Protected fixture outside install');
mkdirSync(protectedTarget);
writeFileSync(path.join(protectedTarget, '__init__.py'), 'protected external fixture');
renameSync(packageModule, preservedModule);
symlinkSync(protectedTarget, packageModule, 'junction');
assert.equal(run(installer, ['/S', '/FIXTURE', `/D=${installed}`]).status, 4);
assert.equal(run(path.join(installed, 'Uninstall-ClipForge.exe'), ['/S', '/FIXTURE', `_?=${installed}`]).status, 4);
assert.equal(readFileSync(path.join(protectedTarget, '__init__.py'), 'utf8'), 'protected external fixture');
unlinkSync(packageModule);
renameSync(preservedModule, packageModule);
const hardLinked = path.join(installed, 'tools/python/Lib/site-packages/psutil/__init__.py');
const savedOriginal = hardLinked + '.preserved-fixture';
renameSync(hardLinked, savedOriginal);
linkSync(path.join(protectedTarget, '__init__.py'), hardLinked);
assert.equal(run(installer, ['/S', '/FIXTURE', `/D=${installed}`]).status, 4);
assert.equal(run(path.join(installed, 'Uninstall-ClipForge.exe'), ['/S', '/FIXTURE', `_?=${installed}`]).status, 4);
assert.equal(readFileSync(path.join(protectedTarget, '__init__.py'), 'utf8'), 'protected external fixture');
unlinkSync(hardLinked);
renameSync(savedOriginal, hardLinked);
const cli = run(path.join(installed, 'tools/python/python.exe'), ['-s', '-B', '-u', path.join(installed, 'app/automation/cli.py')]);
// CLI without JSON input returns an expected structured invalid-input error, proving runtime launches.
assert.equal(cli.status, 0);
assert.equal(JSON.parse(cli.stdout).ok, false);
const uninstall = run(path.join(installed, 'Uninstall-ClipForge.exe'), ['/S', '/FIXTURE', `_?=${installed}`]);
assert.equal(uninstall.status, 0, uninstall.stderr);
assert(!existsSync(path.join(installed, 'ClipForge.exe')));
assert(existsSync(path.join(installed, 'clipforge-portable.json')));
assert.equal(readFileSync(path.join(installed, 'data/preserved/example.txt'), 'utf8'), 'fixture user data');
assert.equal(readFileSync(path.join(installed, 'tools/user-installed/custom.txt'), 'utf8'), 'fixture downloaded helper');
const unrelated = path.join(root, 'Unrelated existing folder');
mkdirSync(unrelated);
writeFileSync(path.join(unrelated, 'keep.txt'), 'existing unrelated data');
const denied = run(installer, ['/S', '/FIXTURE', `/D=${unrelated}`]);
assert.equal(denied.status, 2);
assert(!existsSync(path.join(unrelated, 'ClipForge.exe')));
assert.equal(readFileSync(path.join(unrelated, 'keep.txt'), 'utf8'), 'existing unrelated data');
const linkTarget = path.join(root, 'Junction target');
const link = path.join(root, 'Linked location');
mkdirSync(linkTarget);
symlinkSync(linkTarget, link, 'junction');
const linked = run(installer, ['/S', '/FIXTURE', `/D=${path.join(link, 'ClipForge')}`]);
assert.equal(linked.status, 2);
assert(!existsSync(path.join(linkTarget, 'ClipForge/ClipForge.exe')));
const report = { install: 'passed', lockedApplicationUpdateAndUninstallRejected: 'passed', updatePreservesDataAndAddedHelpers: 'passed', uninstallPreservesDataAndAddedHelpers: 'passed', unrelatedFolderRejected: 'passed', junctionAncestorRejected: 'passed', uninstallJunctionRootRejected: 'passed', internalJunctionAndHardLinkRejected: 'passed', fixtureOnly: true, fixtureRoot: root };
writeFileSync(path.join(path.dirname(installer), 'INSTALLER-VERIFICATION.json'), JSON.stringify(report, null, 2) + '\n');
