import assert from 'node:assert/strict';
import {createMediaBroker} from '../src/clipMediaRequests.ts';
const turn=()=>new Promise(resolve=>setTimeout(resolve,0));
let reads=0,cancels=0,acknowledge;
const completions=[];
const broker=createMediaBroker(()=>{reads++;return new Promise(resolve=>completions.push(resolve));},()=>{cancels++;return new Promise(resolve=>{acknowledge=resolve;});});
const a=broker.acquire('job','clip');
const b=broker.acquire('job','clip');
assert.equal(a.promise,b.promise,'Visible duplicates share one media request');
await turn();
assert.equal(reads,1);
a.release();a.release();b.release();
await turn();
assert.equal(cancels,1,'The last consumer cancels once');
completions[0]('old preview');
await a.promise;
const replacement=broker.acquire('job','clip');
await turn();
assert.equal(reads,1,'A replacement waits even if the old read settles before cancellation acknowledgement');
acknowledge();
await turn();
assert.equal(reads,2);
const peer=broker.acquire('job','clip');
assert.equal(peer.promise,replacement.promise,'The old finalizer cannot delete the replacement');
completions[1]('new preview');
assert.equal(await replacement.promise,'new preview');
replacement.release();peer.release();
const strict=broker.acquire('job','clip');
strict.release();
const remount=broker.acquire('job','clip');
await turn();
assert.equal(cancels,1,'Same-turn StrictMode remount does not cancel shared work');
completions[2]('remount preview');
assert.equal(await remount.promise,'remount preview');
remount.release();
console.log('Media lifecycle checks passed: shared reads, idempotent release, cancellation barrier, identity and StrictMode handoff.');
